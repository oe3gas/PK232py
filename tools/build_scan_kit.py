"""P90: build the scan kit for other radio amateurs.

    python tools/build_scan_kit.py [--out dist] [--date YYYY-MM-DD]

writes dist/pk232_scan_kit_<date>.zip with a STAND-ALONE scanner: tools/pk232_fw_scan.py with the few parts it
needs from PK232PY copied in at BUILD time (the wake-up byte and banner markers of the detection chain,
escape_converse(), verbose_line(), the command matrix reader) and the command matrix itself as an embedded
table. The generated file needs only the standard library and pyserial.

NOT part of the shipped application. Lernmodus: the scanner is the one source of truth - nothing in the kit
is typed twice; the builder cuts the import block out of the tool (between the "pk232py imports" markers)
and puts generated code in its place, so a change in tools/pk232_fw_scan.py or in PK232PY reaches the kit with
the next build. The zip is reproducible: the same sources and --date give the same bytes (fixed time stamps,
sorted entries).
"""

