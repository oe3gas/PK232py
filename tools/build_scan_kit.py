# ---------------------------------------------------------------------------- the standalone scanner

def _literal_lines(name: str, text: str) -> str:
    """A text as a Python expression ``name = ( 'line\\n' ... )``, one literal per line."""
    parts = text.splitlines(keepends=True)
    return f"{name} = (\n" + "".join(f"    {part!r}\n" for part in parts) + ")\n"


def generated_block() -> str:
    """What replaces the pk232py import block: copies of what the scanner uses, made NOW from the live code."""
    devs = tuple((d.label, d.release) for d in devices.KNOWN_DEVICES)
    matrix_csv = MATRIX_CSV.read_text(encoding="utf-8").replace("\r\n", "\n")
    cm_source = Path(command_matrix.__file__).read_text(encoding="utf-8").replace("\r\n", "\n")
    return "\n".join([
        "# ---- generated at build time: what the scanner needs from PK232PY (no pk232py is imported) ----",
        "import types",
        "from typing import Callable",
        "",
        f"VERBOSE_EOL = {constants.VERBOSE_EOL!r}",
        inspect.getsource(constants.verbose_line).rstrip("\n"),
        "",
        f"FRAME_HOST_OFF = {constants.FRAME_HOST_OFF!r}",
        f"FACTORY_BANNER_LINES = {constants.FACTORY_BANNER_LINES!r}",
        inspect.getsource(constants.is_factory_banner).rstrip("\n"),
        "",
        f"_WAKEUP = {serial_manager._WAKEUP!r}",
        f"_BANNER_MARKERS = {serial_manager._BANNER_MARKERS!r}",
        f"_XON_BYTE = {serial_manager._XON_BYTE!r}",
        f"_ESCAPE_CONVERSE_TIMEOUT = {pk232_hostmode_sub._ESCAPE_CONVERSE_TIMEOUT!r}",
        "",
        inspect.getsource(pk232_hostmode_sub.escape_converse).rstrip("\n"),
        "",
        "# the devices known to the project (label, release) - only to name the device in the report",
        f"KNOWN_DEVICES = tuple(types.SimpleNamespace(label=l, release=r) for l, r in {devs!r})",
        "",
        "# the command matrix: its reader (a copy of comm/command_matrix.py) and the matrix as a table",
        _literal_lines("_MATRIX_CSV", matrix_csv),
        _literal_lines("_CM_SOURCE", cm_source),
        "cm = types.ModuleType('command_matrix')",
        "cm.__file__ = 'command_matrix.py (embedded)'   # the copy computes DATA_FILE from it (never read)",
        "sys.modules['command_matrix'] = cm            # dataclasses look the module up by name",
        "exec(compile(_CM_SOURCE, 'command_matrix.py (embedded)', 'exec'), cm.__dict__)",
        "cm.load = lambda path=None: cm.parse(_MATRIX_CSV)      # no data file here: the embedded table",
        "cm._adopt([c[3:] for c in _MATRIX_CSV.split('\\n', 1)[0].split(',') if c.startswith('fw_')])",
        "cm.reload()",
        "# ---- end of the generated block ----",
    ]) + "\n"


def build_standalone_source() -> str:
    """The text of the stand-alone scanner."""
    src = SCANNER.read_text(encoding="utf-8").replace("\r\n", "\n")
    begin, end = src.index(BEGIN), src.index(END)
    src = src[:begin] + generated_block() + src[end + len(END) + 1:]
    assert src.count("\n_KIT = False\n") == 1
    src = src.replace("\n_KIT = False\n", "\n_KIT = True\n")
    head, rest = src.split("\n", 2)[:2], src.split("\n", 2)[2]       # shebang and coding line stay first
    return "\n".join(head + [GENERATED, rest])


def embedded_matrix_text(source: str) -> str:
    """Python text that defines only ``_MATRIX_CSV`` - cut out of a generated scanner (for the tests)."""
    start = source.index("_MATRIX_CSV = (")
    end = source.index("_CM_SOURCE = (")
    return source[start:end]


# ---------------------------------------------------------------------------- the zip

def _device_info_form() -> str:
    text = Path(SCANNER).read_text(encoding="utf-8")
    m = re.search(r'DEVICE_INFO_TEMPLATE = """(.*?)"""', text, re.S)
    template = m.group(1)
    template = template.split("# Filled in by the scanner:")[0]
    return template + f"# {DEVICE_INFO_NOTE}\n"


def kit_files() -> dict:
    """{name in the zip: (bytes, unix mode)}"""
    return {
        "pk232_fw_scan.py": (build_standalone_source().encode("utf-8"), 0o644),
        "requirements.txt": (b"pyserial\n", 0o644),
        "README_DE.md": (README_DE.encode("utf-8"), 0o644),
        "README_EN.md": (README_EN.encode("utf-8"), 0o644),
        "run_scan.bat": (RUN_BAT.replace("\n", "\r\n").encode("utf-8"), 0o644),
        "run_scan.sh": (RUN_SH.encode("utf-8"), 0o755),
        "device_info.txt": (_device_info_form().encode("utf-8"), 0o644),
    }


def build_kit(out_dir, date: str = "") -> Path:
    """dist/pk232_scan_kit_<date>.zip - reproducible for the same sources and date."""
    date = date or _dt.date.today().isoformat()
    y, mo, d = (int(x) for x in date.split("-"))
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    zpath = out_dir / f"pk232_scan_kit_{date}.zip"
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for name, (data, mode) in sorted(kit_files().items()):
            info = zipfile.ZipInfo(name, date_time=(y, mo, d, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (mode & 0xFFFF) << 16
            z.writestr(info, data)
    return zpath


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Build the PK-232 scan kit for external operators")
    ap.add_argument("--out", default=str(REPO / "dist"), help="output directory (default dist/)")
    ap.add_argument("--date", default="", help="date in the file name and the zip (default today)")
    args = ap.parse_args(argv)
    print(f"[+] {build_kit(args.out, args.date)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
